def check_no_arbitrage():
    buy = {}
    for _, _, items in SHOP.values():
        for mat, amount, price, _ in items:
            buy[mat] = price / amount
    for _, _, items in BUYER.values():
        for mat, price, _ in items:
            if mat in buy:
                assert price < buy[mat], f"арбитраж: {mat} продаётся за {price}, покупается за {buy[mat]}"


